import math
from collections import Counter

PLACEHOLDER = "synthetic placeholder - not measured"


def calculate_cohens_kappa(labels_1: list[str], labels_2: list[str]) -> float:
    """Computes Cohen's kappa coefficient between two annotator lists."""
    assert len(labels_1) == len(labels_2), "Annotator lists must have identical length"
    n = len(labels_1)
    if n == 0:
        return 0.0

    categories = sorted(set(labels_1) | set(labels_2))
    p_o = sum(1 for a, b in zip(labels_1, labels_2, strict=True) if a == b) / n
    count_1, count_2 = Counter(labels_1), Counter(labels_2)
    p_e = sum((count_1[cat] / n) * (count_2[cat] / n) for cat in categories)

    if math.isclose(1.0, p_e):
        return 1.0
    return (p_o - p_e) / (1.0 - p_e)


def percentile(data: list[float], pct: float) -> float:
    """Calculates the given percentile of a dataset (linear interpolation)."""
    if not data:
        return 0.0
    sorted_data = sorted(data)
    idx = (len(sorted_data) - 1) * (pct / 100.0)
    lo, hi = math.floor(idx), math.ceil(idx)
    if lo == hi:
        return sorted_data[int(idx)]
    return sorted_data[lo] * (hi - idx) + sorted_data[hi] * (idx - lo)


